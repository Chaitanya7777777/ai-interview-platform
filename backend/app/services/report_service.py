REPORT_VERSION = "1.0.0"


def calculate_report_hash(match: JobMatch) -> str:
    """
    Compute a unique SHA-256 hash of the analysis results + report version
    to check for modifications and facilitate reuse of existing reports.
    """
    payload = {
        "match_score": match.match_score,
        "ats_score": match.ats_score,
        "strengths": match.strengths,
        "missing_keywords": match.missing_keywords,
        "missing_skills": match.missing_skills,
        "recommendations": match.recommendations,
        "role_fit": match.role_fit,
        "interview_readiness": match.interview_readiness,
        "summary": match.summary,
        "job_title": match.job_title,
        "company_name": match.company_name,
        "report_version": REPORT_VERSION,
    }
    serialized = json.dumps(payload, sort_keys=True, default=str)
    return hashlib.sha256(serialized.encode("utf-8")).hexdigest()


